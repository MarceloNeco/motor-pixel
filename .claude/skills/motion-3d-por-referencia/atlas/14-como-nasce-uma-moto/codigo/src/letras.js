// letras.js: letra de arquiteto em traço único, com os acentos do português.
// Cada glifo é uma lista de riscos; cada risco, uma lista de pontos [x, y] numa caixa de altura 1
// (linha de base em y = 0, topo da maiúscula em y = 1). `w` é a largura da letra.
// A ordem dos riscos é a ordem em que a mão escreve.
const arco = (cx, cy, rx, ry, a0, a1) => {
  const n = Math.max(4, Math.ceil(Math.abs(a1 - a0) / 12)), o = [];
  for (let i = 0; i <= n; i++) { const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180; o.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]); }
  return o;
};
